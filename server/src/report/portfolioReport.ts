import { createRequire } from 'node:module';
import path from 'node:path';
import PDFDocument from 'pdfkit';
import { BUCKETS } from '../tools/arrears.js';
import type { PortfolioSummary } from '../tools/portfolio.js';

/** Monthly portfolio report (A4 PDF): KPIs, bucket mix, NPL trend, breakdowns, vintage, roll rates, commentary. */
const C = { ink: '#0f2a3d', ink2: '#3b556a', muted: '#7890a3', line: '#e3eaef', bg: '#f3f6f8', teal: '#0d9488', amber: '#d97706', red: '#dc2626', green: '#16a34a' };
const BUCKET_COLOR: Record<string, string> = { Current: '#10b981', '1-30': '#84cc16', '31-60': '#fbbf24', '61-90': '#f97316', '91-180': '#ef4444', '181+': '#991b1b' };
const require = createRequire(import.meta.url);
const fontDir = path.join(path.dirname(require.resolve('@fontsource/inter/package.json')), 'files');
const PAGE = { w: 595.28, h: 841.89, m: 44 };
const W = PAGE.w - PAGE.m * 2;
type Doc = PDFKit.PDFDocument;

const pct = (x: number, d = 2) => `${(x * 100).toFixed(d)}%`;
const rm = (n: number) => `RM ${Math.round(n).toLocaleString('en-MY')}`;
/** Only characters the font can draw. */
const safe = (s: string) => s.replace(/[→]/g, '->').replace(/\s*[—–]\s*/g, ' - ').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E -ɏ\n]/g, '');

function heading(doc: Doc, text: string) {
  if (doc.y > PAGE.h - 140) doc.addPage();
  doc.moveDown(0.6).font('bold').fontSize(12).fillColor(C.ink).text(text, PAGE.m, doc.y, { width: W }).moveDown(0.3);
}

function table(doc: Doc, head: string[], rows: string[][], widths: number[], alignRightFrom = 1) {
  const rowH = 16;
  const draw = (cells: string[], y: number, bold: boolean) => {
    let x = PAGE.m;
    cells.forEach((c, i) => {
      doc.font(bold ? 'semibold' : 'regular').fontSize(8).fillColor(bold ? C.muted : C.ink2)
        .text(safe(c), x + 3, y + 4, { width: widths[i] - 6, align: i >= alignRightFrom ? 'right' : 'left', lineBreak: false, ellipsis: true });
      x += widths[i];
    });
  };
  if (doc.y + rowH * 2 > PAGE.h - PAGE.m) doc.addPage();
  let y = doc.y;
  draw(head, y, true);
  y += rowH;
  for (const r of rows) {
    if (y + rowH > PAGE.h - PAGE.m) {
      doc.addPage();
      y = PAGE.m;
      draw(head, y, true);
      y += rowH;
    }
    doc.moveTo(PAGE.m, y).lineTo(PAGE.m + W, y).lineWidth(0.4).strokeColor(C.line).stroke();
    draw(r, y, false);
    y += rowH;
  }
  doc.y = y + 6;
}

function markdown(doc: Doc, md: string) {
  for (const raw of md.split('\n')) {
    const line = raw.trimEnd();
    if (!line.trim()) { doc.moveDown(0.3); continue; }
    if (doc.y > PAGE.h - PAGE.m - 30) doc.addPage();
    const h = /^#{1,4}\s+(.*)$/.exec(line);
    const b = /^\s*[-*]\s+(.*)$/.exec(line);
    const n = /^\s*(\d+)[.)]\s+(.*)$/.exec(line);
    const plain = (s: string) => safe(s.replace(/\*\*/g, '').replace(/(^|\s)\*([^*]+)\*/g, '$1$2'));
    if (h) doc.font('bold').fontSize(10).fillColor(C.ink).text(plain(h[1]), PAGE.m, doc.y, { width: W });
    else if (b) doc.font('regular').fontSize(9).fillColor(C.ink2).text(`•  ${plain(b[1])}`, PAGE.m + 8, doc.y, { width: W - 8 });
    else if (n) doc.font('regular').fontSize(9).fillColor(C.ink2).text(`${n[1]}.  ${plain(n[2])}`, PAGE.m + 8, doc.y, { width: W - 8 });
    else doc.font('regular').fontSize(9).fillColor(C.ink2).text(plain(line), PAGE.m, doc.y, { width: W });
  }
}

export async function renderPortfolioReport(opts: {
  month: string;
  summary: PortfolioSummary;
  commentary: string | null;
  trend: Array<{ month: string; nplRatio: number; par30: number }>;
  generatedBy: string;
}): Promise<Buffer> {
  const s = opts.summary;
  const doc = new PDFDocument({ size: 'A4', margins: { top: PAGE.m, bottom: PAGE.m, left: PAGE.m, right: PAGE.m }, info: { Title: `Portfolio report ${opts.month}`, Author: 'Xanderia AI Council' } });
  doc.registerFont('regular', path.join(fontDir, 'inter-latin-400-normal.woff'));
  doc.registerFont('semibold', path.join(fontDir, 'inter-latin-600-normal.woff'));
  doc.registerFont('bold', path.join(fontDir, 'inter-latin-700-normal.woff'));
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => doc.on('end', () => resolve(Buffer.concat(chunks))));

  // Header band
  doc.rect(0, 0, PAGE.w, 110).fill(C.ink);
  doc.font('semibold').fontSize(9).fillColor('#cdf6ee').text('Xanderia AI Council · Portfolio report', PAGE.m, 30);
  doc.font('bold').fontSize(20).fillColor('#ffffff').text(`Loan portfolio, ${opts.month}`, PAGE.m, 46);
  doc.font('regular').fontSize(8.5).fillColor('#c7d4de').text(
    `${s.total.accounts.toLocaleString()} accounts · ${rm(s.total.balance)} outstanding · NPL = ${s.options.nplDays}+ days past due${s.options.restructuredIsNpl && s.columns.restructured ? ', restructured included' : ''} · generated by ${safe(opts.generatedBy)}`,
    PAGE.m, 78, { width: W },
  );
  doc.y = 128;

  // KPI tiles
  const prev = opts.trend.length > 1 ? opts.trend[opts.trend.length - 2] : null;
  const tiles = [
    { big: pct(s.nplRatio), small: `NPL ratio${prev ? ` (${s.nplRatio >= prev.nplRatio ? '+' : ''}${((s.nplRatio - prev.nplRatio) * 100).toFixed(2)} pts)` : ''}`, color: s.nplRatio > 0.05 ? C.red : s.nplRatio > 0.03 ? C.amber : C.green },
    { big: pct(s.par.par30), small: 'PAR30', color: C.ink },
    { big: pct(s.par.par90), small: 'PAR90', color: C.ink },
    { big: rm(s.total.npl.balance), small: `NPL balance (${s.total.npl.accounts.toLocaleString()} account${s.total.npl.accounts === 1 ? '' : 's'})`, color: C.ink },
  ];
  const tw = (W - 18) / 4;
  const ty = doc.y; // text() moves doc.y, so every tile uses the same top
  tiles.forEach((t, i) => {
    const x = PAGE.m + i * (tw + 6);
    doc.roundedRect(x, ty, tw, 54, 6).fill(C.bg);
    doc.font('bold').fontSize(14).fillColor(t.color).text(t.big, x + 10, ty + 10, { width: tw - 20, lineBreak: false });
    doc.font('regular').fontSize(7.2).fillColor(C.muted).text(t.small, x + 10, ty + 34, { width: tw - 20, lineBreak: false, ellipsis: true });
  });
  doc.x = PAGE.m;
  doc.y = ty + 70;

  // Bucket mix bar
  heading(doc, 'Balance by days past due');
  let x = PAGE.m;
  const barY = doc.y;
  for (const b of BUCKETS) {
    const w = s.total.balance ? (s.total.buckets[b].balance / s.total.balance) * W : 0;
    if (w > 0) doc.rect(x, barY, w, 18).fill(BUCKET_COLOR[b]);
    x += w;
  }
  doc.y = barY + 24;
  table(doc, ['Bucket', 'Accounts', 'Balance', '% of balance'], BUCKETS.map((b) => [b, s.total.buckets[b].accounts.toLocaleString(), rm(s.total.buckets[b].balance), pct(s.total.balance ? s.total.buckets[b].balance / s.total.balance : 0, 1)]), [120, 110, 150, W - 380]);

  // NPL trend
  if (opts.trend.length > 1) {
    heading(doc, 'NPL ratio and PAR30, month by month');
    const cx = PAGE.m + 30, cy = doc.y, cw = W - 40, ch = 110;
    const max = Math.max(...opts.trend.map((t) => Math.max(t.nplRatio, t.par30)), 0.01) * 1.15;
    doc.moveTo(cx, cy).lineTo(cx, cy + ch).lineTo(cx + cw, cy + ch).lineWidth(0.6).strokeColor(C.line).stroke();
    for (const [series, color] of [['par30', C.amber], ['nplRatio', C.red]] as const) {
      opts.trend.forEach((t, i) => {
        const px = cx + (i / Math.max(1, opts.trend.length - 1)) * cw;
        const py = cy + ch - (t[series] / max) * ch;
        if (i === 0) doc.moveTo(px, py);
        else doc.lineTo(px, py);
      });
      doc.lineWidth(1.6).strokeColor(color).stroke();
    }
    opts.trend.forEach((t, i) => {
      const px = cx + (i / Math.max(1, opts.trend.length - 1)) * cw;
      doc.font('regular').fontSize(6.5).fillColor(C.muted).text(t.month, px - 20, cy + ch + 3, { width: 40, align: 'center' });
    });
    doc.font('regular').fontSize(7).fillColor(C.red).text(`NPL ${pct(opts.trend.at(-1)!.nplRatio)}`, cx + cw - 80, cy - 2, { width: 80, align: 'right' });
    doc.fillColor(C.amber).text(`PAR30 ${pct(opts.trend.at(-1)!.par30)}`, cx + cw - 80, cy + 8, { width: 80, align: 'right' });
    doc.y = cy + ch + 18;
  }

  const groupTable = (title: string, list: PortfolioSummary['byBranch']) => {
    if (!list.length) return;
    heading(doc, title);
    table(doc, ['Name', 'Accounts', 'Balance', 'NPL balance', 'NPL ratio'], list.slice(0, 12).map((g) => [g.name, g.accounts.toLocaleString(), rm(g.balance), rm(g.npl.balance), pct(g.nplRatio)]), [170, 70, 100, 90, W - 430]);
  };
  groupTable('By branch', s.byBranch);
  groupTable('By product', s.byProduct);
  groupTable('By employer', s.byEmployer);

  if (s.vintage.length) {
    heading(doc, 'Vintage: loans by disbursement quarter');
    table(doc, ['Cohort', 'Accounts', 'Balance', 'NPL ratio', 'PAR30'], s.vintage.slice(-12).map((v) => [v.cohort, v.accounts.toLocaleString(), rm(v.balance), pct(v.nplRatio), pct(v.par30)]), [120, 90, 130, 90, W - 430]);
  }
  if (s.rollRates) {
    heading(doc, `Roll rates vs last month (${s.rollRates.matched.toLocaleString()} accounts matched)`);
    table(doc, ['From bucket', 'Rolled worse', 'Stayed', 'Improved'], s.rollRates.rates.map((r) => [r.from, pct(r.worse, 1), pct(r.same, 1), pct(r.better, 1)]), [140, 120, 120, W - 380]);
  }

  if (opts.commentary) {
    heading(doc, "Council commentary");
    markdown(doc, opts.commentary);
  }
  doc.moveDown(1).font('regular').fontSize(7).fillColor(C.muted).text(
    'Figures are calculated from the uploaded loan export; the commentary is AI-generated advice from the Xanderia AI Council and must be reviewed before decisions are made.',
    PAGE.m, doc.y, { width: W },
  );
  doc.end();
  return done;
}
